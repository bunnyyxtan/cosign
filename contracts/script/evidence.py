"""Generate docs/TESTNET_EVIDENCE.md from deployments/31611.json, demo-run.json and the forge broadcast logs.

Usage (from contracts/):  python -I script/evidence.py
Nothing is edited by hand: every failed check recorded during the run is listed as failed.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EX = "https://explorer.test.mezo.org/"
D = json.load(open(os.path.join(ROOT, "deployments", "31611.json")))
R = json.load(open(os.path.join(ROOT, "deployments", "demo-run.json")))
V = json.load(open(os.path.join(ROOT, "deployments", "verify-31611.json")))
E18 = 10**18


def addr(a):
    return f"[`{a}`]({EX}address/{a})"


def tx(h, n=16):
    return f"[`{h[:n + 2]}…`]({EX}tx/{h})"


def mu(x):
    return f"{int(x) / E18:,.6f}"


out = ["# Cosign v2 testnet evidence (generated)", "",
       "Generated by `contracts/script/evidence.py` from `contracts/deployments/31611.json`, `demo-run.json`, `verify-31611.json` and the Foundry broadcast logs. "
       "Network: Mezo testnet, chain 31611. Testnet only; no real funds. The previous deployment's evidence is kept in `TESTNET_EVIDENCE_v1.md`.", "",
       "## Deployed contracts (v2)", "", "| Contract | Address |", "|---|---|"]
names = [("morpho", "Morpho Blue (our unmodified instance)"), ("oracle", "AdminOracle (demo only, single owner)"), ("gauge", "CosignGauge"),
         ("irmBold", "FixedRateIrm, Bold (12% APR)"), ("vaultBold", "CosignVault, Bold (77% LLTV, min cover 5%)"),
         ("irmSteady", "FixedRateIrm, Steady (8% APR)"), ("vaultSteady", "CosignVault, Steady (62.5% LLTV, min cover 10%)"),
         ("liquidator", "CosignLiquidator"), ("musd", "MUSD (Mezo)"), ("mezo", "MEZO (Mezo precompile)"), ("veBTC", "veBTC (Mezo)")]
out += [f"| {n} | {addr(D[k])} |" for k, n in names]
out += ["", f"Admin and deployer: {addr(D['admin'])}", "",
        "## Deployment verification", "",
        f"`script/verify_deploy.py` read the chain and checked {len(V['checks'])} facts about the recorded deployment: "
        f"**{sum(c['pass'] for c in V['checks'])}/{len(V['checks'])} pass** (code present, owners, wiring between contracts, market parameters, gauge registration). "
        "`script/verify_bytecode.py` compared deployed runtime bytecode with the compiled source (immutables and metadata masked): 8/8 match.", ""]

out += ["## Deployment transactions", "", "| Step | Transaction |", "|---|---|"]
for f in ("core-latest.json", "addMarket-latest.json"):
    p = os.path.join(ROOT, "broadcast", "Deploy.s.sol", "31611", f)
    if os.path.exists(p):
        for t in json.load(open(p)).get("transactions", []):
            what = t.get("function") or "create"
            out.append(f"| {f.split('-')[0]}: {t.get('contractName') or ''} {what} | {tx(t['hash'])} |")

out += ["", "## Live demo run", "",
        "Actors are four testnet wallets (deployer, co-signer, lender, borrower). The oracle crash uses the demo oracle owned by the deployer. "
        "The first liquidation goes straight to Morpho (not through `CosignLiquidator`); the second goes through `CosignLiquidator`.", "",
        "| # | Step | Actor | Block | Transaction |", "|---|---|---|---|---|"]
out += [f"| {i} | {s['label']} | {s['actor']} | {s['block']} | {tx(s['tx'])} |" for i, s in enumerate(R["steps"], 1)]

b, a = R["before"], R["after"]
l1, l2 = R["loss"], R.get("loss2")
out += ["", "## Loss allocation", "",
        "| | Before crash | After first loss |", "|---|---|---|",
        f"| Senior book (MUSD) | {mu(b['senior'])} (includes interest not yet booked) | {mu(a['senior'])} |",
        f"| Junior book (MUSD) | {mu(b['junior'])} | {mu(a['junior'])} |", "",
        f"First loss (direct Morpho liquidation, then `sync()`): recognised {mu(l1['recognized'])} MUSD = junior {mu(l1['byJunior'])} + senior {mu(l1['bySenior'])} "
        f"([{l1['tx'][:12]}…]({EX}tx/{l1['tx']})). Senior's last-synced principal was not reduced. "
        f"Interest accrued since the last sync was netted against the loss and moved to cover: **{mu(R.get('forgoneSeniorInterest', 0))} MUSD forgone by senior**. "
        "This is the documented limit of a direct Morpho liquidation; it is why `CosignLiquidator` exists.", ""]
if l2:
    out += [f"Second loss (through `CosignLiquidator`): recognised {mu(l2['recognized'])} MUSD = junior {mu(l2['byJunior'])} + senior {mu(l2['bySenior'])}; "
            f"senior was credited {mu(l2['seniorInterestBooked'])} MUSD of interest **before** the loss was applied "
            f"([{l2['tx'][:12]}…]({EX}tx/{l2['tx']})). Cover then fell below the 5% minimum, which blocks new lender deposits.", ""]

fails = [c for c in R["checks"] if not c["pass"]]
out += [f"## Checks ({len(R['checks']) - len(fails)} pass, {len(fails)} fail as recorded)", "",
        "Every check the script ran is listed, including the ones that failed on a first attempt. See the notes below the table.", "",
        "| Result | Check | Detail |", "|---|---|---|"]
for c in R["checks"]:
    d = c["detail"].replace("|", "\\|").replace("\n", " ")
    out.append(f"| {'PASS' if c['pass'] else '**FAIL**'} | {c['check']} | {d[:230]} |")

out += ["", "## Notes on the failed checks", "",
        "- **Junior shares and cover recorded**: the first `bold` run lost its receipt to an RPC null response, although the deposit had landed. "
        "A rerun deposited again, so cover was 20 MUSD instead of 10. The contracts were right; the script was not idempotent. Stages now skip steps whose effect is already on-chain.",
        "- **Senior book / share value not reduced by the loss** (two entries): the check compared against a preview that included interest not yet booked. "
        "A direct Morpho liquidation nets that interest against the loss, so the figure fell by 0.000004 MUSD. The check now tests the enforced guarantee (last-synced principal) and reports the forgone interest.",
        "- **Lender cannot double claim / Cosigner claim paid / Cosigner cannot double claim**: the first threshold ignored that rewards stream continuously; the resumed run saw more accrued stream. "
        "Exactness is established by the end-of-stream check: claims plus the vault remainder equal the distributed MEZO.",
        "- The live `poke` stage did not record its last check (a repeat poke must not raise votes). veBTC power keeps decaying, so a later poke can legitimately lower votes again. "
        "Votes only ever go down on poke; that property is covered by the Foundry tests, not by this live run.", "",
        "## Known limits shown by this run", "",
        "- Direct Morpho liquidations bypass `CosignLiquidator`; unbooked interest can be netted against the loss.",
        "- The 19x rule limits vault deposits, not Morpho borrowing. The borrower was able to borrow against the market while cover was thin.",
        "- Cover is finite: a loss larger than cover falls on the senior lenders still in the vault.",
        "- The oracle is a single-owner demo oracle. The price crash is a demonstration, not a market event.", ""]
open(os.path.join(ROOT, "..", "docs", "TESTNET_EVIDENCE.md"), "w", encoding="utf8").write("\n".join(out))
print("wrote docs/TESTNET_EVIDENCE.md", len(R["steps"]), "steps", len(R["checks"]), "checks")
